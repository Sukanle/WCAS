#!/usr/bin/env python3
"""Generate the proxy's Wayland wire metadata from protocol XML.

The C++ proxy must translate objects, fds and `new_id`s on the wire, so it
needs each message's *wire* opcode and signature together with the version the
message was introduced in.

Neither waylandpp's generated `wl_interface` tables nor `libwayland-client`'s
`wl_interface` tables can be used for this:

* libwayland's client tables fold the private `release`/`destroy` request into
  the same opcode as its neighbour, which renumbers every later opcode (for
  example `wl_seat.get_pointer` is opcode 1 there and 0 on the wire).
* waylandpp's tables are generated from the same client-side interfaces.

This generator reads the protocol XML directly, which is the wire definition,
and emits `wire_meta.cpp`/`wire_meta.h`. The generated file is committed so the
build never depends on protocol XML being installed; CMake regenerates it when
`WCAS_REGENERATE_WIRE_META` is on.

Usage:
    generate_wire_meta.py OUTPUT_DIR XML [XML ...]
"""

import os
import sys
import xml.etree.ElementTree as ET

# Wayland wire type codes. `new_id` carries the interface name separately.
TYPE_MAP = {
    "int": "i",
    "uint": "u",
    "fixed": "f",
    "string": "s",
    "object": "o",
    "new_id": "n",
    "array": "a",
    "fd": "h",
}


def build_signature(arguments):
    """Wire signature plus the interface created by a `new_id`, if any.

    The `allow-null` marker belongs to the nearest following argument, so it is
    merged with that argument's type code (`?s`, `?o`) rather than emitted on
    its own.
    """
    signature = ""
    new_interface = None
    for argument in arguments:
        argument_type = argument.get("type")
        code = TYPE_MAP.get(argument_type)
        if code is None:
            raise SystemExit(f"unknown argument type {argument_type!r}")
        nullable = argument.get("allow-null", "false") == "true"
        if nullable and code in ("o", "s"):
            signature += "?"
        if code == "n":
            interface = argument.get("interface")
            if interface:
                new_interface = interface
        signature += code
    return signature, new_interface


def collect(xml_paths):
    """Interfaces keyed by name, first definition wins."""
    interfaces = {}
    for path in xml_paths:
        if not os.path.exists(path):
            raise SystemExit(f"protocol XML not found: {path}")
        root = ET.parse(path).getroot()
        for element in root.findall("interface"):
            name = element.get("name")
            if name in interfaces:
                continue
            requests = []
            for opcode, request in enumerate(element.findall("request")):
                signature, new_interface = build_signature(request.findall("arg"))
                requests.append(
                    {
                        "name": request.get("name"),
                        "signature": signature,
                        "new_interface": new_interface,
                        "since": int(request.get("since", "1")),
                        "opcode": opcode,
                    }
                )
            events = []
            for opcode, event in enumerate(element.findall("event")):
                signature, new_interface = build_signature(event.findall("arg"))
                events.append(
                    {
                        "name": event.get("name"),
                        "signature": signature,
                        "new_interface": new_interface,
                        "since": int(event.get("since", "1")),
                        "opcode": opcode,
                    }
                )
            interfaces[name] = {
                "name": name,
                "version": int(element.get("version", "1")),
                "requests": requests,
                "events": events,
            }
    return interfaces


def cpp_string(value):
    if value is None:
        return "nullptr"
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')


def emit_table(output, symbol, messages, label):
    output.write(f"const MessageMeta {symbol}_{label}[] = {{\n")
    for message in messages:
        output.write(
            "    {%s, %s, %s, %u, %u},\n"
            % (
                cpp_string(message["name"]),
                cpp_string(message["signature"]),
                cpp_string(message["new_interface"]),
                message["since"],
                message["opcode"],
            )
        )
    output.write("};\n\n")


def emit(interfaces, output):
    ordered = [interfaces[name] for name in sorted(interfaces)]
    output.write("// Generated by codegen/generate_wire_meta.py -- DO NOT EDIT.\n")
    output.write("// Source: Wayland protocol XML (the wire definition).\n")
    output.write('#include "SKL/WCAS/Private/Proxy/WireMeta.h"\n\n')
    output.write("namespace skl::wcas::proxy::wire {\n\n")

    for interface in ordered:
        symbol = interface["name"].replace("-", "_").replace(".", "_")
        if interface["requests"]:
            emit_table(output, symbol, interface["requests"], "requests")
        if interface["events"]:
            emit_table(output, symbol, interface["events"], "events")

    output.write("static const InterfaceMeta extension_table[] = {\n")
    for interface in ordered:
        symbol = interface["name"].replace("-", "_").replace(".", "_")
        request_symbol = f"{symbol}_requests" if interface["requests"] else "nullptr"
        event_symbol = f"{symbol}_events" if interface["events"] else "nullptr"
        output.write(
            "    {%s, %u, %s, %u, %s, %u},\n"
            % (
                cpp_string(interface["name"]),
                interface["version"],
                request_symbol,
                len(interface["requests"]),
                event_symbol,
                len(interface["events"]),
            )
        )
    output.write("};\n\n")
    output.write(f"const size_t interface_count = {len(ordered)};\n\n")
    output.write("""const InterfaceMeta* extension_interfaces() {
    return extension_table;
}

size_t extension_interface_count() {
    return interface_count;
}

""")
    output.write("} // namespace skl::wcas::proxy::wire\n")


def main():
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    output_dir = sys.argv[1]
    interfaces = collect(sys.argv[2:])
    os.makedirs(output_dir, exist_ok=True)
    destination = os.path.join(output_dir, "wire_meta.cpp")
    with open(destination, "w") as handle:
        emit(interfaces, handle)
    print(f"wrote {destination} ({len(interfaces)} interfaces)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
